/**
 * Areas: one overworld map each — theme, encounter tables, a semi-boss partway along, the end boss, and the loot
 * tier (gear band, FF9 shops, synthesis tier). Journeys (below) say which areas a run visits.
 */

/**
 * Area themes: the overworld's terrain and colours and the battle background (web `map/terrain.ts`, `map-scene.ts`,
 * `sprites/sprites.ts` each have a row per theme).
 */
export const MAP_THEMES = ["grassland", "forest", "castle", "ice", "cave", "marsh", "ruin", "desert", "volcano", "coast", "town", "crystal"] as const;
export type MapTheme = (typeof MAP_THEMES)[number];

export interface WorldDef {
  /** Position in WORLDS. */
  index: number;
  id: string;
  /**
   * Progression tier, 0–5 (0 Disc 1 early, 1 Disc 1 late, 2 Disc 2, 3 Disc 3, 4 Disc 4, 5 post-game) — gates the camp
   * catalog, supplies, events and specials, not loot. Tables keyed by it treat their last row as "and later".
   */
  tier: number;
  name: string;
  subtitle: string;
  /** Background/tileset key for the overworld and battles. */
  theme: MapTheme;
  /** Normal encounter groups: enemy ids, or an FF9 battle scene ("@EF_R004") whose spawn pattern is rolled like FF9. */
  encounters: string[][];
  /** Elite ("fortress") encounters. */
  elites: string[][];
  /** Optional semi-boss fortress at the middle of the map (every path passes it). Each map's castle boss is
   *  already the "gym leader", so most areas leave this unset. */
  semiBoss?: string[];
  /**
   * Stages per round (column) on this area's map, start to boss — `MAP_SHAPE` when unset. First and last are 1, and
   * neighbouring rounds differ by at most one stage (e.g. a one-stage-per-round gauntlet: [1, 1, 1, 1, 1]).
   */
  mapShape?: number[];
  boss: string[];
  /** Gear price band rewards are drawn from (FF9 shop prices as a power proxy). */
  gearPrice: [number, number];
  /** FF9 equipment shops (ShopItems.csv ids) whose stock appears in this world, in story order. */
  shops: number[];
  /** FF9 general item stores mixed into every shop for consumables. */
  itemStores: number[];
  /** Highest FF9 synthesis shop (32–39) whose recipes are available here. */
  synthTier: number;
}

