#!/usr/bin/env bun
/// <reference types="node" />
/**
 * build-music — ship the FF9 tracks the game uses (`music-map.ts`) from `.docs/assets/FF9/music`
 * (`python scripts/extract-ff9-music.py`): copies each `.ogg` to `public/music/` and writes
 * `src/features/audio/music.gen.ts` with each track's name and FF9's own loop points (read from the AKB header:
 * loop start/end in samples, the two u32s 0x40 bytes before the Ogg stream).
 *
 *   bun scripts/build-music.ts
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { AREA_MUSIC, BOSS_MUSIC, MUSIC_SLOTS } from "./music-map";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, "..", "..", "..", ".docs", "assets", "FF9", "music");
const OUT = join(HERE, "..", "public", "music");
const GEN = join(HERE, "..", "src", "features", "audio", "music.gen.ts");
const SAMPLE_RATE = 44100;

const names = JSON.parse(readFileSync(join(SRC, "names.json"), "utf8")) as Record<string, string>;
const ids = [...new Set([...Object.values(MUSIC_SLOTS), ...Object.values(AREA_MUSIC), ...Object.values(BOSS_MUSIC)])].sort();
mkdirSync(OUT, { recursive: true });
const tracks: Record<string, { url: string; name: string; loopStart: number; loopEnd: number }> = {};
for (const id of ids) {
  const akb = readFileSync(join(SRC, `${id}.akb`));
  const ogg = akb.indexOf("OggS");
  const loopStart = akb.readUInt32LE(ogg - 0x40);
  const loopEnd = akb.readUInt32LE(ogg - 0x3c);
  copyFileSync(join(SRC, `${id}.ogg`), join(OUT, `${id}.ogg`));
  tracks[id] = { url: `/music/${id}.ogg`, name: names[id] ?? id, loopStart: loopStart / SAMPLE_RATE, loopEnd: loopEnd ? (loopEnd + 1) / SAMPLE_RATE : 0 };
}
mkdirSync(dirname(GEN), { recursive: true });
writeFileSync(
  GEN,
  `// Generated by scripts/build-music.ts — do not edit.
/** FF9 tracks: url, name, and FF9's loop points in seconds (loopEnd 0 = loop the whole track). */
export const MUSIC_TRACKS: Record<string, { url: string; name: string; loopStart: number; loopEnd: number }> = ${JSON.stringify(tracks, null, 1)};
export const MUSIC_SLOTS = ${JSON.stringify(MUSIC_SLOTS, null, 1)} as const;
export const AREA_MUSIC: Record<string, string> = ${JSON.stringify(AREA_MUSIC, null, 1)};
export const BOSS_MUSIC: Record<string, string> = ${JSON.stringify(BOSS_MUSIC, null, 1)};
`,
);
console.log(`✓ ${ids.length} tracks → ${OUT}`);
