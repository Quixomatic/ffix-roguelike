/// <reference types="node" />
/**
 * Packs the item icons the game uses (scripts/item-icon-map.ts) from the Time Fantasy icon sheet into one atlas.
 * Only the mapped icons ship with the game — the pack itself stays in `.docs/assets/finalbossblues` (git-ignored).
 *
 * Writes:
 *   public/sprites/items.png                 — 16×16 cells, ATLAS_COLS per row
 *   src/features/items/item-icons.gen.ts     — FF9 item id → cell index
 *
 *   bun scripts/build-item-icons.ts [--tf]   (from apps/web; `pnpm -F web sprites:items`; --tf = the muted
 *                                            "limited colour" Time Fantasy palette instead of full colour)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { PNG } from "pngjs";

import { ITEM_ICONS } from "./item-icon-map";

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PACK = path.resolve(WEB, "../../.docs/assets/finalbossblues/icons_8.13.20");
const SHEET = process.argv.includes("--tf") ? path.join(PACK, "tfcolor/tficons_limited_16.png") : path.join(PACK, "fullcolor/icons_full_16.png");
const OUT = path.join(WEB, "public/sprites/items.png");
const GEN = path.join(WEB, "src/features/items/item-icons.gen.ts");
const CELL = 16;
const ATLAS_COLS = 16;

if (!fs.existsSync(SHEET)) throw new Error(`Time Fantasy icon sheet not found at ${SHEET} (unzip icons_8.13.20.zip there)`);
const sheet = PNG.sync.read(fs.readFileSync(SHEET));

// One cell per distinct sheet icon.
const cells: [number, number][] = [];
const cellOf = new Map<string, number>();
const index: Record<number, number> = {};
for (const [id, rc] of Object.entries(ITEM_ICONS).sort((a, b) => Number(a[0]) - Number(b[0]))) {
  const k = rc.join(",");
  if (!cellOf.has(k)) {
    cellOf.set(k, cells.length);
    cells.push(rc);
  }
  index[Number(id)] = cellOf.get(k)!;
}

const rows = Math.ceil(cells.length / ATLAS_COLS);
const atlas = new PNG({ width: ATLAS_COLS * CELL, height: rows * CELL });
cells.forEach(([r, c], i) => {
  const ox = (i % ATLAS_COLS) * CELL;
  const oy = Math.floor(i / ATLAS_COLS) * CELL;
  for (let y = 0; y < CELL; y++)
    for (let x = 0; x < CELL; x++) {
      const si = ((r * CELL + y) * sheet.width + c * CELL + x) * 4;
      const di = ((oy + y) * atlas.width + ox + x) * 4;
      for (let k = 0; k < 4; k++) atlas.data[di + k] = sheet.data[si + k]!;
    }
});
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, PNG.sync.write(atlas));

fs.mkdirSync(path.dirname(GEN), { recursive: true });
fs.writeFileSync(
  GEN,
  `// Generated by scripts/build-item-icons.ts — do not edit by hand (edit scripts/item-icon-map.ts).\n\n` +
    `/** Item icon atlas at /sprites/items.png: ITEM_ICON_CELL px cells, ITEM_ICON_COLS per row. */\n` +
    `export const ITEM_ICON_CELL = ${CELL};\nexport const ITEM_ICON_COLS = ${ATLAS_COLS};\n` +
    `export const ITEM_ICON_ROWS = ${rows};\n\n` +
    `/** FF9 item id → atlas cell. */\nexport const ITEM_ICON_INDEX: Record<number, number> = ${JSON.stringify(index)};\n`,
);
console.log(`${Object.keys(index).length} items → ${cells.length} icons (${path.relative(WEB, OUT)}), ${path.relative(WEB, GEN)}`);
